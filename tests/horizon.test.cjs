const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const ctx=vm.createContext({console,Date,Intl,Map,Set,Math,Number,String,Array,Error});
vm.runInContext(fs.readFileSync('dist/engine.js','utf8'),ctx);
const E=ctx.MeterEngine,fixture=require('./fixture.cjs');
const a=fixture.apartments[0];
const get=date=>E.predict(a,[],date);
assert.equal(get('2026-10-26').daysAhead,1);
assert.notEqual(get('2026-10-26').model,'Historical daily average');
assert.notEqual(get('2026-10-27').model,'Historical daily average');
const p=get('2026-11-14');
const ds=E.changes(a.readings).filter(x=>!x.flag).map(x=>x.delta);
assert.equal(p.predicted,a.readings.at(-1).value+Math.round(ds.reduce((s,n)=>s+n,0)/ds.length*20));
assert.equal(p.daysAhead,20);
assert.equal(p.model,'Historical daily average');
assert.equal(p.confidence,'Caution');
assert.equal(p.likelihood,null);
assert.ok(p.warnings.some(w=>/20 days/.test(w)));
assert.equal(get('2026-10-29').model,'Historical daily average');
console.log('PASS one-day method preserved; 3+/20-day averages, no misleading multi-day probability, and caution');
