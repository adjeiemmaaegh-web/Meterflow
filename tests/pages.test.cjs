const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.METERFLOW_PAGES_BASE || '/Meterflow/';
const html = fs.readFileSync('dist/index.html', 'utf8');
const manifest = JSON.parse(fs.readFileSync('dist/manifest.webmanifest', 'utf8'));
const app = fs.readFileSync('dist/app.js', 'utf8');
const worker = fs.readFileSync('dist/sw.js', 'utf8');
assert.match(html, new RegExp(`src="${base}app\\.js"`));
assert.match(html, new RegExp(`href="${base}manifest\\.webmanifest"`));
assert.equal(manifest.start_url, base);
assert.equal(manifest.scope, base);
assert.equal(manifest.id, base);
assert.ok(manifest.icons.every(i => i.src.startsWith(base)));
assert.ok(app.includes(`serviceWorker.register('${base}sw.js')`));
const urls = JSON.parse(/const FILES=(\[[^;]+\]);/.exec(worker)[1]);
assert.ok(urls.every(url => url.startsWith(base)));
assert.ok(worker.includes(`caches.match('${base}index.html')`));
assert.ok(!html.includes('src="/app.js"'));
console.log('✓ Pages subpath, install manifest, and offline cache verified.');
